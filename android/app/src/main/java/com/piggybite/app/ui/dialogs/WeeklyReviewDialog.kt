@Composable
fun WeeklyReviewDialog(
    transactions: List<Transaction> = emptyList(),
    onDismiss: () -> Unit,
    onAddManual: () -> Unit
) {
    val isDark = LocalIsDarkMode.current

    val now = System.currentTimeMillis()
    val sevenDaysAgo = now - 7 * 24 * 60 * 60 * 1000L
    val recentTxs = remember(transactions) {
        transactions.filter { it.timestamp >= sevenDaysAgo }
    }
    val expenseTxs = remember(recentTxs) {
        recentTxs.filter { !it.isIncome }
    }
    val totalExpense = remember(expenseTxs) {
        expenseTxs.sumOf { it.amount }
    }
    val autoGeneratedCount = remember(recentTxs) {
        recentTxs.count { it.id.startsWith("tx_auto_") }
    }

    Dialog(
        onDismissRequest = onDismiss,
        properties = DialogProperties(usePlatformDefaultWidth = false)
    ) {
        Surface(
            shape = RoundedCornerShape(topStart = 28.dp, topEnd = 28.dp),
            color = MaterialTheme.colorScheme.surface,
            modifier = Modifier
                .fillMaxSize()
                .padding(top = 40.dp)
        ) {
            Column(
                modifier = Modifier
                    .fillMaxSize()
                    .padding(20.dp)
            ) {
                // Header: Tuần này | Đóng
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.SpaceBetween,
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    Text(
                        text = "Khép sổ tuần này",
                        fontSize = 17.sp,
                        fontWeight = FontWeight.Bold,
                        color = MaterialTheme.colorScheme.onSurface
                    )
                    IconButton(onClick = onDismiss, modifier = Modifier.size(32.dp)) {
                        Icon(
                            imageVector = Icons.Default.Close,
                            contentDescription = "Đóng",
                            tint = if (isDark) DarkTextMuted else Color(0xFF6B7280)
                        )
                    }
                }

                Spacer(modifier = Modifier.height(10.dp))

                LazyColumn(
                    modifier = Modifier
                        .weight(1f)
                        .fillMaxWidth(),
                    verticalArrangement = Arrangement.spacedBy(16.dp)
                ) {
                    // Summary subtitle
                    item {
                        val summaryText = if (recentTxs.isEmpty()) {
                            "Chưa có giao dịch nào được ghi nhận trong tuần này."
                        } else {
                            "Tuần này có ${recentTxs.size} khoản ($autoGeneratedCount khoản PiggyBite tự động nhận diện)."
                        }
                        Text(
                            text = summaryText,
                            fontSize = 14.sp,
                            color = if (isDark) DarkTextMuted else Color(0xFF6B7280),
                            lineHeight = 20.sp
                        )
                    }

                    // Card "Ngoài sổ"
                    item {
                        Column(
                            modifier = Modifier
                                .fillMaxWidth()
                                .clip(RoundedCornerShape(20.dp))
                                .background(if (isDark) DarkCardBackground else Color(0xFFF9FAFB))
                                .border(1.dp, if (isDark) DarkCardBorder else Color(0xFFE5E7EB), RoundedCornerShape(20.dp))
                                .padding(16.dp)
                        ) {
                            Text(
                                text = "Ngoài sổ",
                                fontSize = 12.5.sp,
                                fontWeight = FontWeight.Bold,
                                color = if (isDark) DarkTextMuted else Color(0xFF6B7280)
                            )
                            Spacer(modifier = Modifier.height(6.dp))
                            Text(
                                text = "Có khoản tiền mặt nào chưa kịp ghi không?",
                                fontSize = 14.sp,
                                fontWeight = FontWeight.SemiBold,
                                color = MaterialTheme.colorScheme.onSurface
                            )

                            Spacer(modifier = Modifier.height(14.dp))

                            Row(
                                modifier = Modifier.fillMaxWidth(),
                                horizontalArrangement = Arrangement.SpaceBetween,
                                verticalAlignment = Alignment.CenterVertically
                            ) {
                                Text(
                                    text = "Bù khoản chi tiền mặt",
                                    fontSize = 13.sp,
                                    color = if (isDark) DarkTextMuted else Color(0xFF6B7280)
                                )
                                Text(
                                    text = "+ Ghi tay",
                                    fontSize = 13.5.sp,
                                    fontWeight = FontWeight.Bold,
                                    color = if (isDark) DarkTitleBlue else SkyBluePrimary,
                                    modifier = Modifier.clickable { onAddManual() }
                                )
                            }
                        }
                    }

                    // Card "Khoản chi tiêu tuần này"
                    item {
                        Column(
                            modifier = Modifier
                                .fillMaxWidth()
                                .clip(RoundedCornerShape(20.dp))
                                .background(if (isDark) DarkCardBackground else Color(0xFFF9FAFB))
                                .border(1.dp, if (isDark) DarkCardBorder else Color(0xFFE5E7EB), RoundedCornerShape(20.dp))
                                .padding(16.dp)
                        ) {
                            Text(
                                text = "Giao dịch chi tiêu trong 7 ngày qua (${expenseTxs.size})",
                                fontSize = 12.5.sp,
                                fontWeight = FontWeight.Bold,
                                color = if (isDark) DarkTextMuted else Color(0xFF6B7280)
                            )
                            Spacer(modifier = Modifier.height(12.dp))

                            if (expenseTxs.isEmpty()) {
                                Text(
                                    text = "Chưa có khoản chi tiêu nào trong tuần.",
                                    fontSize = 13.sp,
                                    color = if (isDark) DarkTextSub else Color(0xFF9CA3AF)
                                )
                            } else {
                                val sdf = SimpleDateFormat("dd/MM • HH:mm", Locale.getDefault())
                                expenseTxs.take(6).forEach { tx ->
                                    Row(
                                        modifier = Modifier
                                            .fillMaxWidth()
                                            .padding(vertical = 6.dp),
                                        horizontalArrangement = Arrangement.SpaceBetween,
                                        verticalAlignment = Alignment.CenterVertically
                                    ) {
                                        Column {
                                            Text(
                                                text = tx.note.ifBlank { tx.category },
                                                fontSize = 13.5.sp,
                                                fontWeight = FontWeight.SemiBold,
                                                color = MaterialTheme.colorScheme.onSurface
                                            )
                                            Text(
                                                text = "${tx.bankName} • ${sdf.format(Date(tx.timestamp))}",
                                                fontSize = 11.5.sp,
                                                color = if (isDark) DarkTextSub else Color(0xFF9CA3AF)
                                            )
                                        }
                                        Text(
                                            text = "-${Formatters.formatMoney(tx.amount)}",
                                            fontSize = 13.5.sp,
                                            fontWeight = FontWeight.Bold,
                                            color = MaterialTheme.colorScheme.onSurface
                                        )
                                    }
                                }
                            }
                        }
                    }

                    // Total spending
                    item {
                        Row(
                            modifier = Modifier
                                .fillMaxWidth()
                                .clip(RoundedCornerShape(16.dp))
                                .background(if (isDark) DarkCardBackground else Color.White)
                                .border(1.dp, if (isDark) DarkCardBorder else Color(0xFFE5E7EB), RoundedCornerShape(16.dp))
                                .padding(16.dp),
                            horizontalArrangement = Arrangement.SpaceBetween,
                            verticalAlignment = Alignment.CenterVertically
                        ) {
                            Text(
                                text = "Tổng chi tuần này",
                                fontSize = 14.sp,
                                color = if (isDark) DarkTextMuted else Color(0xFF6B7280)
                            )
                            Text(
                                text = Formatters.formatMoney(totalExpense),
                                fontSize = 17.sp,
                                fontWeight = FontWeight.Bold,
                                color = MaterialTheme.colorScheme.onSurface
                            )
                        }
                    }
                }

                Spacer(modifier = Modifier.height(14.dp))

                // Action Buttons: Đóng
                Column(
                    modifier = Modifier.fillMaxWidth(),
                    verticalArrangement = Arrangement.spacedBy(8.dp),
                    horizontalAlignment = Alignment.CenterHorizontally
                ) {
                    Button(
                        onClick = onDismiss,
                        modifier = Modifier
                            .fillMaxWidth()
                            .height(50.dp),
                        shape = RoundedCornerShape(16.dp),
                        colors = ButtonDefaults.buttonColors(
                            containerColor = if (isDark) DarkButtonBg else SkyBluePrimary,
                            contentColor = if (isDark) DarkTitleBlue else Color.White
                        ),
                        border = androidx.compose.foundation.BorderStroke(
                            1.dp,
                            if (isDark) DarkButtonBorder else Color.Transparent
                        )
                    ) {
                        Text(
                            text = "Đã xem xong",
                            fontSize = 15.sp,
                            fontWeight = FontWeight.Bold
                        )
                    }
                }
            }
        }
    }
}
